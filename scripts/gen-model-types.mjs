// Generates packages/engine-client/src/model.generated.ts from the checked-in JSON Schema of the project document
// (crates/model, `project.schema.json`). `--check` fails when the checked-in TypeScript is stale. No dependencies.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const ROOT = new URL("../", import.meta.url);
export const SCHEMA_PATH = fileURLToPath(new URL("packages/engine-client/schema/project.schema.json", ROOT));
export const OUT_PATH = fileURLToPath(new URL("packages/engine-client/src/model.generated.ts", ROOT));

const doc = (d, indent = "") => (d ? `${indent}/** ${d.replace(/\*\//g, "* /")} */\n` : "");

function type(s) {
  if (s.$ref) return s.$ref.replace("#/$defs/", "");
  if (s.anyOf) return s.anyOf.map(type).join(" | ");
  if (s.enum) return s.enum.map((v) => JSON.stringify(v)).join(" | ");
  if (Array.isArray(s.type)) return s.type.map((t) => type({ ...s, type: t })).join(" | ");
  switch (s.type) {
    case "null": return "null";
    case "string": return "string";
    case "boolean": return "boolean";
    case "integer": case "number": return "number";
    case "array": return `${type(s.items)}[]`;
    case "object": return objectType(s, "  ");
  }
  throw new Error(`gen-model-types: unsupported schema ${JSON.stringify(s)}`);
}

function objectType(s, indent) {
  const req = new Set(s.required ?? []);
  const lines = Object.entries(s.properties ?? {}).map(
    ([k, v]) => `${doc(v.description, indent)}${indent}${k}${req.has(k) ? "" : "?"}: ${type(v)};\n`,
  );
  return `{\n${lines.join("")}${indent.slice(2)}}`;
}

export function generate(schema) {
  const defs = { [schema.title]: schema, ...schema.$defs };
  const out = ["// GENERATED by scripts/gen-model-types.mjs from schema/project.schema.json. Do not edit.\n",
    "// Time values are integer ticks (ADR 0010); they fit a JS number up to ~147 days, beyond that use the engine.\n"];
  for (const name of Object.keys(defs).sort()) {
    const d = defs[name];
    const body = d.type === "object" ? objectType(d, "  ") : type(d);
    out.push(`\n${doc(d.description)}export ${d.type === "object" ? "interface" : "type"} ${name}${d.type === "object" ? " " : " = "}${body}${d.type === "object" ? "" : ";"}\n`);
  }
  return out.join("");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = generate(JSON.parse(readFileSync(SCHEMA_PATH, "utf8")));
  if (process.argv.includes("--check")) {
    let cur = "";
    try { cur = readFileSync(OUT_PATH, "utf8"); } catch { /* missing */ }
    if (cur !== text) { console.error("model.generated.ts is stale: run `npm run gen:model-types`"); process.exit(1); }
  } else writeFileSync(OUT_PATH, text);
}
